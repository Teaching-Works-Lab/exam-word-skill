# -*- coding: utf-8 -*-
"""卷面标注答案卷交付门禁（exam-word-skill §11.6，题数/分值/缩进全自适应）。

独立于生成器，从成品 DOCX 反查内容，避免「自己生成自己判」。不假定题数、
大题数、章节名、满分分布或缩进常量：客观题/主观题按「题目后是否出现统一
答案标签」自动区分，分值合计与各题题干的「（N 分）」对照，缩进取卷面首个
小问的实际值。

    python scripts/verify_answer_keyed_paper.py out.docx [--spec keyed-spec.json] [--json]

CHECKS 中任何一项失败即 valid=false 并列出 errors。可供 --spec 的派生 spec
做题数交叉校验；未提供时从卷面自适应。
"""
import argparse
import json
import re
import sys
import zipfile
from pathlib import Path

from docx import Document
from docx.text.paragraph import Paragraph
from lxml import etree

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
RUBRIC_LABEL = "参考答案与评分要点："
AI_MARKS = (
    "AI生成", "由 AI 生成", "部分内容可能由 AI 生成", "由人工智能生成",
    "本试卷由 AI", "本文档由 AI", "generated by", "Generated by",
    "ChatGPT 生成", "Claude 生成", "通义千问生成", "文心一言生成",
)
BARE_LABELS = re.compile(r"^\s*(答案：|参考答案\s*$|评分要点\s*$)")
BAD_MARK = re.compile(r"（\d+分）|\(\d+\s*分\)|（\d+\s{2,}分）|\d+\s*分（")
GOOD_MARK = re.compile(r"^（(\d+) 分）")
# 兼容三种卷面写法：C&C++/人工智能「（N 分）正文」；智能制造「【要点】（N 分）正文」
ANY_MARK = re.compile(r"（(\d+)\s*分）")
FULL_MARK = re.compile(r"（(\d+)\s*分）")
CHAPTER = re.compile(r"^[一二三四五六七八九十]、")
QUESTION = re.compile(r"^\d+\s*[、.．]")
SUBQ = re.compile(r"^\s*(?:\([1-9]\)|（[1-9]）|[①②③④⑤⑥⑦⑧⑨⑩])")
BRACKET = re.compile(r"[（(]\s*([^）)]*)\s*[)）]")
ANSWER_TOKEN = re.compile(r"^[A-Z√×]+$")


def txt(el):
    return "".join(t.text or "" for t in el.iter(W + "t"))


def body_items(doc):
    """按文档顺序返回 (kind, object, text)。

    kind: p=顶层段落；tbl=表格（文本为全表拼接，供题目切分）；
    cell-p=表格单元格内段落（供标签/分值要点识别）。
    """
    out = []
    for el in doc.element.body:
        tag = el.tag.split("}")[-1]
        if tag == "p":
            out.append(("p", Paragraph(el, doc._body), txt(el)))
        elif tag == "tbl":
            out.append(("tbl", el, txt(el)))
            # 表格内段落也纳入（答案块可能插在单元格内）
            for p in el.iter(W + "p"):
                out.append(("cell-p", Paragraph(p, doc._body), txt(p)))
    return out


def mark_of(text):
    """从一条要点文本中取分值；兼容生成态与人工修订态，取不到返回 None。

    生成态是行首 `（N 分）`；人工修订态位置自由：`【标题】（N 分）`、
    `①标签（N 分）：`、`（1）链路（4分）：`、`表述合理（1分）`，甚至分值
    落在长句末尾。调用方只在答案区内逐段取分值，不会碰到题干满分，因此
    这里一律取段内第一个 `（N 分）`，避免把合法手改误判成缺分值。
    写法是否规范由 mark_format 单独判，不在此处放宽。
    """
    m = ANY_MARK.search(text.strip())
    return int(m.group(1)) if m else None


def docprops_text(path):
    with zipfile.ZipFile(path) as z:
        out = ""
        for name in ("docProps/core.xml", "docProps/app.xml", "docProps/custom.xml"):
            if name in z.namelist():
                out += z.read(name).decode("utf-8", "ignore")
        return out


def split_questions(items):
    """按题号切题，返回 [(kind, start_index, end_index, stem_text)]。

    兼容两种版式：段落题（题干在 w:p）与表格行题（一大题一表、一行一题）。
    表格题的 start/end 指向该表格元素，stem 为行内文本，用 ' | ' 拼接。
    """
    starts = []
    for i, (kind, obj, text) in enumerate(items):
        s = text.strip()
        if kind == "p" and QUESTION.match(s) and not CHAPTER.match(s):
            starts.append(i)
        elif kind == "tbl":
            # 表格题：从单元格文本里提取所有题号行，作为一个复合 question
            first_line = s.splitlines()[0] if s else ""
            if QUESTION.match(first_line):
                starts.append(i)
    questions = []
    for j, s in enumerate(starts):
        e = starts[j + 1] if j + 1 < len(starts) else len(items)
        for k in range(s + 1, e):
            if items[k][0] == "p" and CHAPTER.match(items[k][2].strip()):
                e = k
                break
        questions.append((items[s][0], s, e, items[s][2].strip()))
    # 表格复合 question 拆成逐题（每题一行，继承表格范围）
    expanded = []
    for kind, s, e, stem in questions:
        if kind == "tbl":
            for line in stem.splitlines():
                if QUESTION.match(line.strip()):
                    expanded.append(("tbl", s, e, line.strip()))
        else:
            expanded.append((kind, s, e, stem))
    return expanded


def run(path, spec_path=None):
    errors, checks = [], {}
    doc = Document(str(path))
    items = body_items(doc)
    paras = [t for k, _, t in items if k in ("p", "cell-p")]
    text = "\n".join(paras)
    props = docprops_text(path)
    questions = split_questions(items)

    def check(name, ok, detail=""):
        checks[name] = {"ok": bool(ok), "detail": "pass" if ok else str(detail)}
        if not ok:
            errors.append(f"{name}: {detail}")

    # 1 卷头：卷别后带「答案」，学生卷卷头三件套保留（卷别不限 A/B）
    head = "\n".join(paras[:6])
    check("answer_label", bool(re.search(r"（[A-Z]\s*卷）\s*答案", head)),
          "卷头未见「（X 卷）答案」")
    check("student_header",
          all(k in head for k in ("序号", "学号", "姓名", "专业及班级")),
          "学号/姓名栏缺失")

    # 2 得分表：保留，得分行为空（不假定行数、不要求满分行为空）
    tbl_ok, detail = False, "无得分表"
    if doc.tables:
        rows = [[c.text.strip() for c in r.cells] for r in doc.tables[0].rows]
        detail = str(rows)
        first_ok = bool(rows) and rows[0][0] == "题号"
        score_rows = [r for r in rows if r and r[0] == "得分"]
        tbl_ok = first_ok and len(score_rows) >= 1 and all(
            v == "" for r in score_rows for v in r[1:])
    check("score_table_blank", tbl_ok, detail)

    # 3 题目分类：题目范围内出现统一标签 → 主观题；否则客观题
    # 表格版式（一大题一表）里一个表格含多道主观题，按该范围内的标签数展开
    objective, subjective = [], []
    for kind, s, e, stem in questions:
        # 人工修订态可能用裸标签（答案：/ 参考答案），也须识别为主观题，
        # 否则会把主观题当客观题、误报「未填答」。标签是否统一由 rubric_labels 单独判。
        label_idxs = [k for k in range(s, e)
                      if items[k][0] in ("p", "cell-p") and
                      (items[k][2].strip() == RUBRIC_LABEL or BARE_LABELS.match(items[k][2].strip()))]
        if not label_idxs:
            objective.append((stem, s, e))
        else:
            # 每道主观题对应一个标签：满分按表格题干行顺序取
            stems = [ln.strip() for ln in stem.splitlines() if QUESTION.match(ln.strip())] or [stem]
            for j, li in enumerate(label_idxs):
                sub_stem = stems[j] if j < len(stems) else stem
                end = label_idxs[j + 1] if j + 1 < len(label_idxs) else e
                subjective.append((sub_stem, li, end))

    unfilled = []
    for stem, s, e in objective:
        brackets = BRACKET.findall(stem)
        last = brackets[-1].strip() if brackets else ""
        if not (last and ANSWER_TOKEN.match(last)):
            unfilled.append(stem[:50])
    check("objective_answers", len(objective) > 0 and not unfilled,
          f"客观题 {len(objective)} 题，未填答 {unfilled}")
    check("objective_count_sane", len(objective) > 0,
          f"未识别到客观题（题数 {len(objective)}）")

    # 4 主观题：每题恰有一个统一标签，无手改式裸标签
    labels = [p.strip() for p in paras if p.strip() == RUBRIC_LABEL]
    bare = [p.strip() for p in paras if BARE_LABELS.match(p)]
    check("rubric_labels",
          len(subjective) > 0 and len(labels) == len(subjective) and not bare,
          f"主观题 {len(subjective)} / 统一标签 {len(labels)} / 裸标签 {bare}")

    # 5 分值：整数、统一「（N 分）」；要点合计 == 该题题干满分（若题干标注）
    bad = BAD_MARK.findall(text)
    sums, fulls, marks_per_q, self_check = [], [], [], []
    for stem, s, e in subjective:
        marks = []
        for k in range(s, e):
            t = items[k][2].strip()
            v = mark_of(t)
            if v is not None:
                marks.append(v)
        marks_per_q.append(marks)
        sums.append(sum(marks))
        fm = FULL_MARK.search(stem)
        fulls.append(int(fm.group(1)) if fm else None)
        # 自洽：要点分值均为正整数、合计与得分表满分行对齐
        self_check.append(bool(marks) and all(m > 0 for m in marks))
    check("mark_format", not bad, f"不规范分值写法 {bad[:5]}")
    check("mark_marks_positive", all(self_check),
          f"要点分值解析 {marks_per_q}")
    comparable = [(a, b) for a, b in zip(sums, fulls) if b is not None]
    # 题干未标满分时（如《智能制造装备》《人工智能技术及应用》卷），
    # 回退到得分表「满分」行做总分校验
    table_total = None
    if doc.tables:
        for r in doc.tables[0].rows:
            cells = [c.text.strip() for c in r.cells]
            if cells and cells[0] in ("满分", "分数") and cells[-1].isdigit():
                table_total = int(cells[-1])
                break
    # 章节标题回退：「四、简答题（共 4 题，每题 10 分，共 40 分）」→ 每题 10 分
    # 每道主观题向上找自己所属章节，取该章「每题 N 分」，避免混入客观题章节
    chapter_fulls = []
    if not comparable:
        for _, s, e in subjective:
            j = s - 1
            while j >= 0:
                hs = items[j][2].strip()
                if j < s and CHAPTER.match(hs):
                    m = re.search(r"每[小]?题\s*(\d+)\s*分", hs)
                    if m:
                        chapter_fulls.append(int(m.group(1)))
                        break
                j -= 1
    if comparable:
        sum_ok = all(a == b for a, b in comparable)
        detail = f"各题要点合计 {sums} / 题干满分 {fulls}"
    elif len(chapter_fulls) == len(sums):
        sum_ok = all(a == b for a, b in zip(sums, chapter_fulls))
        detail = f"各题要点合计 {sums} / 章节满分 {chapter_fulls}"
    elif table_total is not None:
        sum_ok = sum(sums) == table_total
        detail = f"要点合计 {sum(sums)} / 得分表满分 {table_total}"
    else:
        sum_ok, detail = False, "既无题干满分也无章节满分/得分表满分，无法校验"
    check("mark_sum", sum_ok, detail)

    # 6 标签必须绑定首条要点：keep_with_next + 文档顺序下一段是分值要点
    unbound = []
    for i, (kind, obj, t) in enumerate(items):
        if kind not in ("p", "cell-p") or t.strip() != RUBRIC_LABEL:
            continue
        nxt = items[i + 1] if i + 1 < len(items) else ("", None, "")
        ns = nxt[2].strip()
        has_mark = mark_of(ns) is not None
        if not getattr(obj.paragraph_format, "keep_with_next", False) or not has_mark:
            unbound.append(i)
    check("label_bound_to_bullet", not unbound, f"未绑定首条要点的标签 {unbound}")

    # 7 标签不能错位到章标题之后（§11 派生插入点规则）
    misplaced = []
    for i, (kind, obj, t) in enumerate(items):
        if kind not in ("p", "cell-p") or t.strip() != RUBRIC_LABEL:
            continue
        prev = items[i - 1] if i > 0 else ("", None, "")
        if prev[0] == "p" and CHAPTER.match(prev[2].strip()):
            misplaced.append(i)
    check("label_position", not misplaced, f"标签紧跟章标题（错位）{misplaced}")

    # 8 无残留答题空白（空段且段后间距异常）
    with zipfile.ZipFile(path) as z:
        root = etree.fromstring(z.read("word/document.xml"))
    blank_big = 0
    for p in root.iter(W + "p"):
        if txt(p).strip():
            continue
        pPr = p.find(W + "pPr")
        sp = pPr.find(W + "spacing") if pPr is not None else None
        if sp is not None and int(sp.get(W + "after", "0") or 0) > 800:
            blank_big += 1
    check("no_answer_space", blank_big == 0, f"残留大段空白 {blank_big} 处")

    # 9 小问逐行缩进：取卷面首个小问的实际缩进为期望，检查一致性
    subq, in_answer = [], False
    for kind, obj, t in items:
        if kind not in ("p", "cell-p"):
            continue
        s = t.strip()
        if s == RUBRIC_LABEL:
            in_answer = True
            continue
        if in_answer and QUESTION.match(s):
            in_answer = False
        if in_answer or not SUBQ.match(t):
            continue
        pf = obj.paragraph_format
        subq.append(pf.left_indent.twips if pf.left_indent is not None else None)
    expect = subq[0] if subq else None
    check("subquestion_indent", not subq or all(x == expect for x in subq),
          f"期望 {expect} / 实际 {set(subq)}")

    # 10 无硬分页
    page_breaks = sum(1 for br in root.iter(W + "br") if br.get(W + "type") == "page")
    check("no_hard_page_break", page_breaks == 0, f"硬分页 {page_breaks} 处")

    # 11 AI 痕迹（正文 + docProps）
    hits = [m for m in AI_MARKS if m in text or m in props]
    check("no_ai_marks", not hits, f"命中 {hits}")

    # 可选：与派生 spec 交叉校验题数
    if spec_path:
        spec = json.loads(Path(spec_path).read_text(encoding="utf-8-sig"))
        st = spec.get("stats", {})
        if "objective_filled" in st:
            check("spec_objective_match", st["objective_filled"] == len(objective),
                  f"spec {st['objective_filled']} / 卷面 {len(objective)}")
        if "subjective" in st:
            check("spec_subjective_match", len(st["subjective"]) == len(subjective),
                  f"spec {len(st['subjective'])} / 卷面 {len(subjective)}")

    application = ""
    if "docProps/app.xml" in zipfile.ZipFile(path).namelist():
        with zipfile.ZipFile(path) as z:
            app = z.read("docProps/app.xml").decode("utf-8", "ignore")
        m = re.search(r"<Application>([^<]*)</Application>", app)
        application = m.group(1) if m else ""
    return {
        "output": str(path), "valid": not errors, "errors": errors, "checks": checks,
        "paragraphs": len(paras), "objective_count": len(objective),
        "subjective_count": len(subjective), "mark_sums": sums,
        "full_marks": fulls, "subquestion_indent_twips": expect,
        "application": application,
    }


def main():
    ap = argparse.ArgumentParser(description="Verify an answer-keyed exam paper (§11.6)")
    ap.add_argument("docx")
    ap.add_argument("--spec")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()
    report = run(Path(args.docx), Path(args.spec) if args.spec else None)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print("valid:", report["valid"])
        for name, c in report["checks"].items():
            print(f"  {'OK ' if c['ok'] else 'FAIL'} {name}: {c['detail']}")
        for e in report["errors"]:
            print("  ERROR", e)
    return 0 if report["valid"] else 1


if __name__ == "__main__":
    sys.exit(main())
